def build_young_pilot_content(module_id: str, lesson_id: str, lesson_title: str, index: int) -> dict:
    """
    Construit le contenu pédagogique complet d'une leçon 7-9 ans.
    """
    if lesson_id in PILOT_LESSONS_7_9:
        return PILOT_LESSONS_7_9[lesson_id]

    profile = MODULE_PROFILES_7_9.get(module_id)
    if not profile:
        return {}

    idx = min(index, len(profile["activities"]) - 1)
    activity = profile["activities"][idx]

    return {
        "mission": profile["missions"][idx],
        "objectives": [
            f"Expliquer « {lesson_title.lower()} » avec mes mots.",
            f"Réussir une activité sur {profile['theme']}.",
            "Créer une petite production et justifier mon choix."
        ],
        "discover": profile["discoveries"][idx],
        "example": profile["example"],
        "activity": activity,
        "remember": profile["remember"],
        "vocabulary": profile["vocabulary"],
        "challenge": profile["challenges"][idx],
        "skill": profile["skills"][idx],
        "questions": [
            {
                "question": activity["prompt"],
                "options": activity["options"],
                "correct": activity["correct"],
                "explain": activity["success"]
            },
            {
                "question": f"Quel réflexe aide le mieux pendant « {lesson_title} » ?",
                "options": [profile["remember"][0], "Partager un secret", "Répondre sans observer"],
                "correct": 0,
                "explain": profile["remember"][0]
            },
            {
                "question": "Que faire si Palou donne une réponse étrange ?",
                "options": [
                    "La croire sans réfléchir",
                    "Observer, vérifier et demander de l’aide si nécessaire",
                    "La partager immédiatement"
                ],
                "correct": 1,
                "explain": "Un Petit Explorateur observe, vérifie et garde un humain responsable dans la décision."
            }
        ]
    }
